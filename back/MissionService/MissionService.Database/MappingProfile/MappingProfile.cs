using AutoMapper;
using MissionService.Contracts.DataContracts.Mission;
using MissionService.Contracts.Enums;
using MissionService.Database.Models.Contracts;
using MissionService.Database.Models.DbModels;
using MissionService.Database.Models.ViewModel;

namespace MissionService.Database.MappingProfile
{
    /// <summary>
    /// Класс конфигурации маппера
    /// </summary>
    public class MappingProfile : Profile
    {
        public MappingProfile()
        {
            #region Missions

            CreateMap<CreateOneRealMissionContract, Mission>()
                //.ForMember(dest => dest.CreatedUserId,
                //    opt => opt.MapFrom(x => x.UserId))
                .ForMember(dest => dest.Status,
                    opt => opt.MapFrom(x => MissionStatus.New));

            CreateMap<CreateOneMissionFromMapDbContract, Mission>()
                .ForMember(dest => dest.Status,
                    opt => opt.MapFrom(x => MissionStatus.New));

            CreateMap<CreateOneAutoGeneratedMissionModel, Mission>()
                //.ForMember(dest => dest.CreatedUserId,
                //    opt => opt.MapFrom(x => x.CreatedUserId))
                //.ForMember(dest => dest.CreatorType,
                //opt => opt.MapFrom(x => CreatorType.System))
                .ForMember(dest => dest.Status,
                    opt => opt.MapFrom(x => MissionStatus.New));
                //.ForMember(dest => dest.Type,
                //    opt => opt.MapFrom(x => AppType.Real));

            CreateMap<Mission, MissionHistory>()
                .ForMember(dest => dest.Id,
                    opt => opt.Ignore());

            CreateMap<Mission, MissionViewModel>();

            #endregion

            #region Apps

            CreateMap<CreateAppDbContract, App>()
                .ForMember(dest => dest.Type,
                    opt => opt.MapFrom(x => (byte)x.Type));

            CreateMap<App, AppHistory>()
                .ForMember(dest => dest.Id,
                    opt => opt.Ignore());

            CreateMap<App2Mission, App2MissionHistory>()
                .ForMember(dest => dest.Id,
                    opt => opt.Ignore());

            #endregion
        }
    }
}